/* LA TORTA DEL RE · 3 — DALLA CUCINA AL FORNO

   ── LE DUE PAGINE PRIMA, IN UNA NOTTE SOLA ──
   Si riparte da dove comincia la pagina 1: la ladra in camera a mani
   vuote, Grugno al forno, la chiave della dispensa e l'osso per terra in
   cucina. E si va fino in fondo alla pagina 2: la farina in dispensa,
   sotto il naso di Zanna, le uova nel pollaio di Berta, e la ladra
   davanti al vecchio forno con le due cose in mano. Le stanze sono
   quelle della pagina 2, casella per casella; le abitudini di tutti
   sono quelle della pagina 2, parola per parola. Il piano è lungo, ed è
   voluto: si scrive a pezzi — la cucina, poi la porta, poi la dispensa,
   poi il cortile — e ogni pezzo si prova prima di attaccare il dopo.

   ── LA REGOLA, IN UNA FRASE ──
   Il mestolo di Grugno è la cena di Zanna: la porta della dispensa si
   passa fra un mestolo e l'altro.
   Nelle pagine prima il mestolo diceva una cosa per volta. In pagina 1
   «Grugno è al pentolone, la cucina è libera»; in pagina 2 «Zanna va a
   mangiare dietro la porta». Qui le dice tutte e due nello stesso
   battito, e la ladra che attraversa la cucina al mestolo arriva alla
   porta proprio mentre Zanna è a tavola. La chiamata della principessa
   invece ferma l'orologio di Grugno, e con lui la cena di Zanna: finché
   lui è via, il mestolo dopo non suona.

   ── DOVE LA CUCINA TOCCA LA DISPENSA, E VICEVERSA ──
     · Il primo mestolo arriva prima della chiamata. Grugno parte dal
       forno, come in pagina 1, e batte il mestolo al sedicesimo battito;
       la principessa arriva nella sala al diciassettesimo. Quando lei lo
       chiama, Zanna sta andando a mangiare: la ladra che parte dalla
       camera arriva alla porta a cena finita, quella che aspettava sulla
       porta della cucina e corre rischia di trovarla ancora lì.
     · Da dove chiami Grugno decide quanto dura la strada libera, e
       quando Zanna torna alla ciotola. Dalla sala da pranzo lui sta via
       una trentina di battiti, e il mestolo dopo suona a ladra già in
       cortile. Dal corridoio sotto la cucina lo si chiama prima del
       mestolo, e lui tornando lo batte subito: Zanna arriva alla ciotola
       con la ladra sulla porta. Dal pentolone la chiamata dura niente, e
       Grugno torna al forno con la ladra ancora in cucina.
     · Al mestolo Zanna viene alla ciotola per mangiare, non per l'osso:
       l'osso posato lì non lo raccoglie finché non ha finito, e se
       intanto vede la ladra la morde. L'esca funziona fra un mestolo e
       l'altro, non durante.
     · Quello che prendi in cucina decide come passi in dispensa: con
       l'osso si fa l'esca; senza, si aspetta la pappa di Zanna.
     · E la dispensa detta il passo alla cucina: la ladra non vede
       dietro la porta chiusa, e deve ricordarsi dal mestolo che Zanna
       potrebbe essere ancora a tavola. È l'unico verso contrario che
       conta: il cigolio della porta, che in pagina 2 chiamava Grugno
       dalla tavola, qui non cambia l'esito di nessun piano provato (vedi
       sotto), perché la ladra arriva alla porta sempre con Grugno lontano
       — o già addosso.

   ── LE STRADE (le quattro soluzioni qui sotto) ──
     · LA CHIAMATA PER TUTTO — Micio va da Berta; la principessa chiama
       Grugno dalla sala; la ladra, quando la sente, prende la chiave e
       l'osso, apre la dispensa, mette l'osso nella ciotola, prende la
       chiave del cortile e la farina, esce, prende le uova e va al forno.
       È quella che l'ultimo aiuto svela: 61 battiti.
     · LA PAPPA DI ZANNA — senza osso. La ladra aspetta che sia arrivata
       la chiamata, entra, prende la chiave del cortile e si ferma nel
       corridoio di sotto; al mestolo dopo Zanna va a mangiare, e la
       farina resta sola. 88 battiti.
     · GUARDA LA CUCCIA — la stessa pappa, guardata invece che ascoltata:
       la ladra parte quando non vede più Zanna. 90 battiti.
     · LE UOVA PRIMA — la pappa col giro rovesciato: dentro alla chiamata,
       fuori per le uova (Berta sta dietro a Micio e non la guarda), e
       dentro di nuovo per la farina quando suona il mestolo. 93 battiti.
     E le varianti che vincono lo stesso: la principessa può chiamare da
     qualunque punto della sala da pranzo, e anche a ogni mestolo; la
     ladra può aspettare in camera o nel corridoio di sotto; chiave e osso
     in qualunque ordine, e dentro la chiave del cortile prima o dopo la
     farina; con l'osso nella ciotola si possono prendere anche prima le
     uova e poi la farina; Micio da qualunque punto da cui Berta lo veda.
     C'è anche la strada delle due finestre, per chi vuole tenersi il
     trucco della pagina 1: la ladra prende chiave e osso al mestolo e
     torna nel corridoio, la principessa parte per la sala quando sente il
     mestolo e chiama arrivata lì. Vince, ma al battito: se la principessa
     chiama con Grugno fra il forno e la tavola, lui va nella sala passando
     davanti alla porta della cucina, e una ladra che si è fermata troppo
     vicino se lo trova addosso (è la regola della pagina 1).

   ── LE MOSSE INGENUE, E PERCHÉ PERDONO ──
     · partire subito: Grugno è al forno, a due passi dalla chiave;
     · la pagina 2 com'era, «prendi chiave e osso» prima della chiamata:
       adesso stanno in cucina, e in cucina c'è Grugno;
     · la pagina 1 e poi avanti, «al mestolo, vai» dalla porta della
       cucina: in cucina si passa, ma alla porta della dispensa c'è Zanna;
     · guardare Grugno e partire quando non lo vedi più (la strada della
       pagina 1): la porta si apre proprio al mestolo, e Zanna arriva alla
       ciotola con la ladra ancora a tre passi; e chi prende prima l'osso
       passa a tre caselle dalla tavola, dove Grugno sta ancora;
     · chiamarlo dalla camera, dal corridoio, dalla tavola: arriva dove
       passa la ladra;
     · chiamarlo da vicino al pentolone: la strada libera dura troppo
       poco (vedi sopra);
     · la pappa della pagina 2 com'era, due ascolti armati insieme: il
       primo mestolo arriva prima della chiamata e manda la ladra verso
       la farina, con la dispensa ancora chiusa; lei si ferma davanti alla
       porta ad aspettare che qualcuno apra, la chiamata aspetta il suo
       turno, e quando finalmente parte Grugno è già tornato;
     · l'osso posato fuori dalla ciotola, o dopo aver preso la farina;
     · Micio lasciato dov'è, o fermato dove Berta non lo vede;
     · dimenticare la chiave del cortile.

   ── LA MAPPA ──
   È quella della pagina 2, senza una casella cambiata. Di diverso c'è
   solo chi sta dove: la chiave torna vicino al forno e l'osso davanti
   alla porta della dispensa, dove li mette la pagina 1 (e come in pagina
   1 stanno su una casella di pavimento semplice); Grugno parte dal forno
   e non dal pentolone; la ladra parte in camera a mani vuote.

   ── COME È STATA TARATA ──
   Non è stato spostato niente: le abitudini, le stanze e le partenze
   sono quelle delle due pagine, e l'unica manopola rimasta era la
   pagina stessa — le parole e gli aiuti. Nessuna abitudine nuova: il
   legame fra le due metà c'era già (il mestolo che è la pappa di Zanna
   è la catena della pagina 2), e l'unione lo mette in mezzo alla
   strada invece che in fondo. Il cigolio di Grugno resta perché è suo,
   ma su tutta la griglia qui sotto toglierlo non cambia l'esito di un
   solo piano.
   Grugno al forno è proprio la partenza che la pagina 2 aveva scartato
   (il primo mestolo cade due battiti prima della chiamata): lì era una
   coincidenza da togliere, qui è il punto in cui le due metà si
   toccano, e il gioco lo mostra invece di nasconderlo.
   La griglia finale ha 501 piani. Dei 387 sensati — la chiamata dalla
   sala da pranzo, la ladra che aspetta in camera o nel corridoio di
   sotto, l'osso nella ciotola o la pappa, le uova prima o dopo, Micio
   dove Berta lo vede — ne vincono 386, fra 56 e 97 battiti; quello che
   perde è la cuccia guardata dal corridoio con la chiamata più corta
   della sala, cioè la ladra arriva alla porta con Zanna ancora a
   mangiare. Dei 114 ingenui ne vincono 46, e 33 sono la stessa
   famiglia: la ladra che aspetta sulla porta della cucina e corre alla
   chiamata vince 33 volte su 42, e perde le altre nove per il motivo
   detto sopra — arriva a cena non finita. È il punto debole del
   livello, e non ha una manopola che lo tolga senza toccare la partenza
   della pagina 1: lo dice il terzo aiuto («non c'è fretta»). Le altre
   eccezioni sono la chiamata corta che vince quando la ladra prende
   prima la chiave, quasi sempre aspettando nel corridoio (cinque su
   ventiquattro), e due famiglie che vincono dalla camera o dal
   corridoio perché sono la chiamata per tutto con un altro via: la
   ladra che parte al mestolo mentre la principessa chiama dalla sala
   (due battiti prima), e la principessa che chiama solo al mestolo (un
   giro dopo). */

