/* LA TORTA DEL RE — ANDATA E RITORNO

   ── LA STORIA ──
   Domani è il compleanno del re e la principessa vuole fargli una torta a
   sorpresa. La ladra prende la chiave della dispensa e l'osso nella cucina
   di Grugno, la farina nella dispensa dove dorme Zanna, le uova nel pollaio
   dell'oca Berta — e poi le riporta in camera, da dove era partita. Dal
   cortile non si esce: la strada del ritorno ripassa dalla dispensa e dalla
   cucina, e intanto Grugno è tornato al suo giro.

   ── LA REGOLA, IN UNA FRASE ──
   Una chiamata per andare e una per tornare: il mestolo dice quando.
   Il giro di Grugno — forno, tavola, pentolone — adesso guarda sempre la
   strada fra la porta della dispensa e il corridoio della camera: il
   pentolone sta proprio lì accanto. Non c'è un momento del giro in cui
   passare: Grugno se ne va solo se lo chiamano. La principessa dalla sala
   non vede la ladra, ma sente il mestolo, e al mestolo Grugno è al
   pentolone: se lo chiama ogni volta che lo sente, la cucina si svuota una
   volta per l'andata e una per il ritorno. La ladra fa la sua parte
   ascoltando: parte alla prima chiamata, si nasconde in dispensa, e torna
   alla prima chiamata che arriva quando è nascosta.

   ── DOVE L'ANDATA TOCCA IL RITORNO ──
     · L'osso. La porticina del cortile sta sotto la cuccia di Zanna, e si
       passa due volte. L'osso lasciato nella ciotola all'andata è quello che
       Zanna ha ancora in bocca al ritorno: senza, la pappa di Zanna al
       mestolo basta per uscire, ma rientrando con le uova la ladra le passa
       sotto il naso. Senza osso non si vince (è una delle `verifiche`).
     · La porta della dispensa. La ladra la apre all'andata e resta aperta:
       al ritorno Grugno dal forno vede dentro fino alla ciotola. Chi aspetta
       lì la chiamata del ritorno viene preso; un passo più in là no.
     · La principessa è già in sala: la stessa abitudine — «quando senti il
       mestolo, chiama» — fa tutte e due le chiamate. È la catena del
       livello: il mestolo di Grugno fa partire la chiamata della principessa,
       e la chiamata fa partire la ladra.
     · Un ascolto si arma quando la fila ci arriva (§2.5 della guida). Chi
       mette l'andata dentro «quando senti la chiamata» e aggiunge un secondo
       ascolto per il ritorno se li trova armati tutti e due alla prima
       chiamata: il secondo parte appena finisce il primo, cioè la ladra
       torna subito, con Grugno a casa. Si scrive «aspetta che è arrivata la
       chiamata», poi l'andata, poi l'ascolto del ritorno.

   ── LE STRADE (le soluzioni qui sotto) ──
     · A OGNI MESTOLO — la principessa va in sala e chiama Grugno ogni volta
       che sente il mestolo; Micio va al nido a farsi guardare da Berta; la
       ladra, alla prima chiamata, prende la chiave e l'osso, apre la
       dispensa, mette l'osso nella ciotola, prende la chiave del cortile e la
       farina, apre la porticina, prende le uova, torna alla porticina e
       aspetta lì la chiamata del ritorno per andare in camera. È quella che
       l'ultimo aiuto svela: 153 battiti. Il primo mestolo (16) suona prima
       che la principessa arrivi in sala, e la prima chiamata parte al
       secondo (41); la chiamata dell'87 trova la ladra ancora intorno al
       pollaio, col suo ascolto non ancora armato, e va a vuoto — è giusto
       così: la ladra torna con quella del 133.
     · PRIMA LE UOVA — la stessa, col giro rovesciato: fuori per le uova
       prima, la farina al ritorno; la farina sta davanti alla porticina, e
       la ladra aspetta lì. 152 battiti.
     · TORNA AL MESTOLO — la ladra ascolta il mestolo invece della chiamata:
       parte un battito prima di Grugno, ma è ancora in fondo alla dispensa.
       152 battiti.
     · SUBITO, E POI A OGNI MESTOLO — la principessa chiama appena arrivata
       in sala, senza aspettare il primo mestolo. Vince prima (129 battiti),
       ed è quella che scrive chi parte dalla vecchia pagina e aggiunge
       «quando senti il mestolo»; ma la prima chiamata è un ordine che si
       può togliere, e `unita/generale` non accetta una soluzione così
       nemmeno marcata `lunga`: sta qui e non fra le soluzioni.
     E le varianti che vincono lo stesso: la principessa chiama da qualunque
     punto della sala (dalla cucina la strada libera dura meno: dal fondo a
     ovest, dove c'era il pentolone, vince sempre, dagli altri punti dipende
     dall'andata); la ladra aspetta la prima chiamata in camera o in fondo al
     corridoio; chiave e osso in qualunque ordine, la chiave del cortile
     prima o dopo la farina; la chiamata del ritorno si aspetta ovunque in
     dispensa (tranne la ciotola), alla porticina, sulla cuccia accanto a
     Zanna, appena fuori in cortile; Micio al nido o davanti al cancelletto
     del pollaio, e anche solo quando sente la prima chiamata.

   ── LE MOSSE INGENUE, E PERCHÉ PERDONO ──
     · l'andata di prima e poi «vai in camera»: Grugno è tornato al suo giro,
       e il giro guarda la strada — presa da Grugno;
     · tornare al mestolo senza la seconda chiamata: al mestolo Grugno è al
       pentolone, accanto al corridoio — presa da Grugno;
     · guardare Grugno dalla dispensa e partire quando non lo si vede più: va
       dal forno alla tavola, e dalla tavola vede la strada — presa da Grugno;
     · due chiamate di fila: la seconda arriva mentre Grugno corre alla prima,
       e va persa; la ladra aspetta una chiamata che non arriva più;
     · la principessa richiama, ma la ladra torna senza aspettarla (dritta in
       camera, o un ascolto solo per andata e ritorno, o due ascolti armati
       insieme): arriva in cucina con Grugno a casa — presa da Grugno;
     · l'andata dentro «quando senti la chiamata», e il ritorno in un secondo
       ascolto armato dopo le uova: il primo ascolto riparte alla seconda
       chiamata (vuole di nuovo la chiave e l'osso), il secondo gli si mette
       in fila dietro, e la ladra resta in giro — presa da Grugno;
     · aspettare la chiamata del ritorno alla ciotola: Grugno dal forno vede
       dentro la porta aperta — presa da Grugno;
     · aspettarla al nido: la strada è troppo lunga, e Grugno torna al
       pentolone mentre lei passa — presa da Grugno;
     · chiamare dalla camera, dal corridoio, dalla tavola, dal forno, dal
       pentolone, dal mezzo della cucina: Grugno arriva dove passa la ladra;
     · partire subito, o aspettare sulla porta della cucina: il pentolone la
       vede;
     · senza osso (la pappa di Zanna, le uova prima, la principessa che
       finge il mestolo dalla dispensa): fuori ci si arriva, ma rientrando
       dalla porticina Zanna, senza osso, morde; e chi aspetta fuori la cena
       di Zanna per rientrare deve poi aspettare che finisca di mangiare
       davanti alla porta, e intanto Grugno torna — presa da Grugno;
     · l'osso posato fuori dalla ciotola, o tenuto in mano fino alla farina:
       Zanna non ce l'ha quando la ladra passa sotto la cuccia;
     · Micio lasciato dov'è, o fermato dove Berta non lo vede dal nido.

   ── LA MAPPA ──
   Quella di prima con quattro cose spostate, ognuna per un motivo:
     · il pentolone (e il suo braciere) passa da ovest della cucina a
       accanto al corridoio della camera (8,6). Col pentolone a ovest il
       mestolo lasciava la strada libera per una decina di battiti a ogni
       giro, e la ladra che tornava dritta senza nessun accordo passava per
       caso: due piani su tre. Era l'uscita banale di prima, nel tempo invece
       che nello spazio. Adesso nessun momento del giro è libero, e l'unico
       modo è una chiamata. Dove c'era il pentolone c'è una botte;
     · la porticina del cortile passa da (14,4) a (16,4), sotto la farina e
       a tre passi dalla cuccia: la strada del cortile, andata e ritorno,
       passa sotto il naso di Zanna, ed è così che l'osso conta due volte;
     · il pollaio si sposta di una colonna a est e apre il cancelletto a
       est: per le uova si gira intorno al recinto, sei passi in più per
       parte. Con la strada più corta la ladra che tornava subito incrociava
       per caso la seconda chiamata (vedi sotto);
     · l'osso passa da davanti alla porta della dispensa (9,2) a sotto il
       forno (9,4), fra la chiave e la porta: chiave e osso stanno in fila
       sulla stessa strada, e l'ordine in cui li prendi non cambia i tempi.
   Il vecchio forno nel cortile non c'è più. Grugno parte dal forno, come
   prima: il primo mestolo suona prima che la principessa arrivi in sala.

   ── COME È STATA TARATA ──
   Le abitudini sono quelle di prima, parola per parola: nessuna nuova. Il
   ritorno non ne chiedeva una — bastava che il giro di Grugno coprisse la
   strada — e il legame fra le due metà c'era già: l'osso di Zanna.
   Il lavoro è stato togliere le coincidenze, in quest'ordine:
     1. Con la mappa di prima e l'arrivo in camera, la ladra che tornava
        dritta senza nessuna seconda chiamata vinceva due volte su tre:
        arrivava in cucina proprio al mestolo. Col pentolone accanto al
        corridoio: 0 su 9.
     2. Con la principessa che chiama a ogni mestolo, la cucina è libera
        quasi metà del tempo, e la ladra che tornava senza aspettare la
        seconda chiamata ci cadeva dentro per caso: 100 piani su 288 (dritta,
        un ascolto solo, due ascolti, l'ascolto del mestolo armato subito),
        tutti con la principessa che chiama solo al mestolo (a quel punto
        Grugno partiva dal pentolone). Allungare la strada del pollaio
        sposta la banda di arrivo di quei piani, ma non la toglie: i piani
        che chiamano subito e quelli che chiamano solo al mestolo hanno due
        fasi diverse, e la banda finiva sempre nella finestra di uno dei due
        (provato da zero a otto colonne in più). L'ha tolta la combinazione:
        il pollaio col cancelletto a est, Grugno che parte dal forno (il
        primo mestolo cade prima che la principessa arrivi in sala, e le due
        fasi si avvicinano) e l'osso sulla strada.
     3. L'osso davanti alla porta faceva prendere prima l'osso e poi tornare
        indietro per la chiave: sei battiti in più, la porta aperta con
        Grugno di ritorno a cinque passi, il cigolio sentito, e tutto il giro
        di Grugno spostato. All'andata vinceva per due passi, e al ritorno
        faceva vincere per caso la ladra che non aspettava: 18 su 54. Con
        l'osso fra la chiave e il forno i due ordini costano quasi lo stesso.
   Il cigolio di Grugno resta perché è suo: dalla sala non cambia l'esito di
   nessun piano (`--confronta` su tutta la griglia); conta solo per chi
   chiama dalla cucina, dove la strada libera è già al limite.
   La griglia finale: 8.632 piani sensati — due modi di chiamare, undici
   punti da cui chiamare, quattro ordini dell'andata, sei posti per Micio,
   tredici nascondigli, due partenze, due segnali per tornare. Dalla sala
   vincono tutti gli 8.112, fra 119 e 164 battiti; dalla cucina a ovest 386
   su 520 — sempre da (3,3), dove c'era il pentolone, e dagli altri punti
   dipende dall'andata. E 457 piani ingenui, che perdono tutti. */

